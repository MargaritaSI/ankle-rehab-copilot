/** Детерминированная «тарелка дня» по дате YYYY-MM-DD. */
export function plateOfDay(dateIso: string): Plate | null {
  if (PLATES.length === 0) return null;
  let h = 0;
  for (const ch of dateIso) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return PLATES[h % PLATES.length];
}

const MEAL_LABEL: Record<PlateMeal, string> = {
  breakfast: "🌅 Завтрак",
  lunch: "☀️ Обед",
  dinner: "🌙 Ужин",
  snack: "🍎 Перекус",
};

export function mealLabel(meal: PlateMeal): string {
  return MEAL_LABEL[meal];
}

/** Экранирование для Telegram HTML (локальное, без связи с util.ts). */
function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** Telegram-HTML (экранированный) текст тарелки. */
export function renderPlate(p: Plate): string {
  const items = p.items.map((i) => `• ${esc(i)}`).join("\n");
  return `🍽 <b>${esc(p.title)}</b>\n${MEAL_LABEL[p.meal]}\n\n${items}\n\n<i>${esc(p.how)}</i>`;
}

/** Все тарелки для приёма пищи (в порядке объявления). */
export function platesFor(meal: PlateMeal): Plate[] {
  return PLATES.filter((p) => p.meal === meal);
}

/** Следующая тарелка того же приёма после `afterId` (по кругу). */
export function nextPlate(meal: PlateMeal, afterId: string): Plate {
  const list = platesFor(meal);
  if (list.length === 0) return PLATES[0];
  const idx = list.findIndex((p) => p.id === afterId);
  return list[(idx + 1) % list.length];
}
