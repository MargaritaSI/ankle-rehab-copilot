/** Telegram HTML: заголовок, тело, последняя строка — дисклеймер. */
export function renderCard(c: Card): string {
  return `<b>${escapeHtml(c.title)}</b>\n\n${escapeHtml(c.body)}\n\n<i>${CARD_DISCLAIMER}</i>`;
}

/** Inline-клавиатура: одна кнопка на карточку, callback legq:<i>. */
export function cardsKeyboard(): InlineKeyboardMarkup {
  return {
    inline_keyboard: CARDS.slice(0, 10).map((c, i) => [
      { text: c.title, callback_data: `legq:${i}` },
    ]),
  };
}
