export function isBanned(code: string): boolean {
  return STAGE_BANNED.has(code);
}

export function filterSafe(ids: string[]): string[] {
  return ids.filter((id) => !STAGE_BANNED.has(id));
}

export function substituteFor(code: string): string | null {
  const sub = SUBSTITUTES[code];
  return sub && !STAGE_BANNED.has(sub) ? sub : null;
}

/**
 * Убрать запрещённое из набора и, если осталось < minSize, добрать заменами
 * (без дублей). Возвращает безопасный список и признак, что что-то вырезали.
 */
export function sanitizeIds(
  ids: string[],
  minSize = 2,
): { ids: string[]; removed: string[] } {
  const removed = ids.filter((id) => STAGE_BANNED.has(id));
  const safe = Array.from(new Set(filterSafe(ids)));
  if (safe.length < minSize) {
    for (const r of removed) {
      const sub = substituteFor(r);
      if (sub && !safe.includes(sub)) safe.push(sub);
      if (safe.length >= minSize) break;
    }
  }
  return { ids: safe, removed };
}

